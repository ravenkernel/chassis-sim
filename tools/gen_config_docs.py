def _defaults() -> dict[str, str]:
    out: dict[str, str] = {}
    for field in dataclasses.fields(EnvConfig):
        default = field.default
        if (
            default is dataclasses.MISSING
        ):  # pragma: no cover - EnvConfig has no factories
            raise SystemExit(
                f"{field.name} has no default; the reference table needs one"
            )
        if isinstance(default, str):
            out[field.name] = default
        else:
            out[field.name] = repr(default)
    return out


def _validate() -> None:
    keys = [name for _, _, names in GROUPS for name in names]
    dupes = sorted({name for name in keys if keys.count(name) > 1})
    missing = sorted(set(_defaults()) - set(keys))
    unknown = sorted(set(keys) - set(_defaults()))
    for label, names in (
        ("duplicate", dupes),
        ("ungrouped", missing),
        ("unknown", unknown),
    ):
        if names:
            raise SystemExit(f"{label} fields: {', '.join(names)}")
    for table, label in ((EN, "EN"), (ZH, "ZH")):
        blank = sorted(set(keys) - set(table))
        extra = sorted(set(table) - set(keys))
        if blank or extra:
            raise SystemExit(f"{label} descriptions: missing {blank}, extra {extra}")


def render(lang: str) -> str:
    _validate()
    defaults = _defaults()
    header = (
        "| Field | Default | Meaning |\n| --- | --- | --- |"
        if lang == "en"
        else "| 字段 | 默认值 | 说明 |\n| --- | --- | --- |"
    )
    text = {"EN": EN, "ZH": ZH}[lang.upper()]
    lines = [BEGIN]
    for en_title, zh_title, names in GROUPS:
        lines.append("")
        lines.append(f"**{en_title if lang == 'en' else zh_title}**")
        lines.append("")
        lines.append(header)
        for name in names:
            lines.append(f"| `{name}` | `{defaults[name]}` | {text[name]} |")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def splice(readme: Path, lang: str) -> str:
    body = readme.read_text(encoding="utf-8")
    start, end = body.find(BEGIN), body.find(END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit(f"{readme.name}: config-reference markers not found")
    head, tail = body[:start], body[end + len(END) :]
    return head + render(lang) + tail


TARGETS = (("README.md", "en"), ("README.zh-CN.md", "zh"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if a README is stale"
    )
    args = parser.parse_args(argv)
    stale = []
    for name, lang in TARGETS:
        path = REPO / name
        expected = splice(path, lang)
        if args.check:
            if expected != path.read_text(encoding="utf-8"):
                stale.append(name)
        else:
            path.write_text(expected, encoding="utf-8")
            print(
                f"wrote {name} ({lang}): {len(GROUPS)} groups, {len(_defaults())} fields"
            )
    if stale:
        print(
            f"stale: {', '.join(stale)} (run python tools/gen_config_docs.py)",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
